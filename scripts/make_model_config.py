"""Write a pocket-tts model config for the Japanese model.

Starts from the English 24-layer teacher config (architecture, Mimi, and — for training —
the weights the FlowLM is warm-started from) and sets the Japanese tokenizer plus the
inference-time text handling that matches pocket_tts_ja.text.normalize:

  - replace_characters: 。、！？, full-width ASCII, brackets/quotes (stock pocket-tts applies
    this table before tokenizing; it cannot run NFKC itself)
  - capitalize_first_letter: false (no case in Japanese)
  - append_terminal_punctuation: true (adds an ASCII "." like the training text has)
  - remove_semicolons: true

    uv run python scripts/make_model_config.py --vocab 8000 --layers 24 \
        --tokenizer data/tokenizer/ja_8k.model --out configs/model/ja_24l_8k.yaml
"""

import argparse
from pathlib import Path

import yaml

from pocket_tts_ja.mimi_utils import DEFAULT_CONFIG
from pocket_tts_ja.text import inference_replace_characters


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vocab", type=int, required=True)
    parser.add_argument("--layers", type=int, default=24)
    parser.add_argument("--tokenizer", type=str, required=True)
    parser.add_argument("--weights", type=str, default=None, help="default: the English teacher")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    cfg = yaml.safe_load(DEFAULT_CONFIG.read_text())
    if args.weights:
        cfg["weights_path"] = args.weights
        cfg.pop("weights_path_without_voice_cloning", None)
    cfg["flow_lm"]["transformer"]["num_layers"] = args.layers
    cfg["flow_lm"]["lookup_table"].update(
        {"n_bins": args.vocab, "tokenizer": "sentencepiece", "tokenizer_path": args.tokenizer}
    )
    cfg["capitalize_first_letter"] = False
    cfg["append_terminal_punctuation"] = True
    cfg["remove_semicolons"] = True
    cfg["replace_characters"] = inference_replace_characters()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Japanese Pocket TTS model config, generated by scripts/make_model_config.py.\n"
        "# Text handling mirrors pocket_tts_ja.text.normalize for the stock inference code.\n"
    )
    args.out.write_text(header + yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
